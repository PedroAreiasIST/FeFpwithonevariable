!=============================================================================
! NPICARD_GUO_KERNEL -- the energy of the PLA model of Section 8.1.2 (transversely isotropic matrix with voids):
! void fraction from the driving force, driving force (largest transverse stretch), and the energy with its
! stress SE = 2 dW/dCE and DSEDCE. Generated by AceGen; the changes to the generated statements are the names,
! PURE and the declared intents. Tensor components {11,22,33,12,13,23}.
!=============================================================================
module npicard_guo_kernel
   implicit none
   private
   public :: npg_voidfromforce, npg_drivingforce, npg_modifiedse
contains
   PURE SUBROUTINE NPG_VOIDFROMFORCE(VV0,VVO,VVN,E0,EBAR,FORCE)
     IMPLICIT NONE
     DOUBLE PRECISION VV0,VVO,VVN,E0,EBAR,FORCE
     INTENT(IN) :: VV0, VVO, E0, EBAR, FORCE
     INTENT(OUT) :: VVN
     VVN=MAX(VVO,1D0-(1D0-VV0)*DEXP(-(MAX(0D0,-E0+((-1D0)+FORCE)/2D0)/EBAR)))
   END SUBROUTINE NPG_VOIDFROMFORCE

   PURE SUBROUTINE NPG_DRIVINGFORCE(A0,CE,LPER2)
     IMPLICIT NONE
     DOUBLE PRECISION V(79),A0(3),CE(6),LPER2
     INTENT(IN) :: A0, CE
     INTENT(OUT) :: LPER2
     V(70)=A0(1)**2
     V(69)=A0(3)**2
     V(68)=A0(2)**2
     V(13)=1D0/(V(68)+V(69)+V(70))
     V(71)=A0(1)*V(13)
     V(14)=A0(2)*V(71)
     V(29)=-(CE(4)*V(14))
     V(15)=A0(3)*V(71)
     V(36)=-(CE(5)*V(15))
     V(28)=1D0-V(13)*V(68)
     V(18)=A0(2)*A0(3)*V(13)
     V(37)=-(CE(6)*V(18))
     V(33)=-(CE(5)*V(14))-CE(3)*V(18)+CE(6)*V(28)
     V(32)=CE(2)*V(28)+V(29)+V(37)
     V(31)=-(CE(1)*V(14))-CE(5)*V(18)+CE(4)*V(28)
     V(34)=1D0-V(13)*V(69)
     V(73)=V(34)*V(37)
     V(72)=V(34)*V(36)
     V(21)=1D0-V(13)*V(70)
     V(25)=-(CE(6)*V(14))-CE(3)*V(15)+CE(5)*V(21)
     V(24)=-(CE(2)*V(14))-CE(6)*V(15)+CE(4)*V(21)
     V(23)=CE(1)*V(21)+V(29)+V(36)
     V(22)=V(21)*V(23)-V(14)*V(24)-V(15)*V(25)
     V(26)=-(V(14)*V(23))-V(18)*V(25)+V(24)*V(28)
     V(56)=(V(26)*V(26))
     V(47)=(-2D0)*V(56)
     V(27)=-(V(15)*V(23))-V(18)*V(24)+V(25)*V(34)
     V(55)=(V(27)*V(27))
     V(48)=(-2D0)*V(55)
     V(30)=-(V(14)*V(31))+V(28)*V(32)-V(18)*V(33)
     V(35)=-(V(15)*V(31))-V(18)*V(32)+V(33)*V(34)
     V(54)=(V(35)*V(35))
     V(49)=(-2D0)*V(54)
     V(38)=CE(1)*(V(15)*V(15))+2D0*CE(4)*V(15)*V(18)+CE(2)*(V(18)*V(18))+CE(3)*(V(34)*V(34))+2D0*V(72)+2D0*V(73)
     V(39)=(V(22)+V(30)+V(38))/3D0
     V(40)=V(22)-V(39)
     V(50)=(V(40)*V(40))
     V(41)=V(30)-V(39)
     V(51)=(V(41)*V(41))
     V(42)=V(38)-V(39)
     V(52)=(V(42)*V(42))
     V(43)=0D0
     IF(2D0*(V(26)*V(26))+2D0*(V(27)*V(27))+2D0*(V(35)*V(35))+(V(40)*V(40))+(V(41)*V(41))+(V(42)*V(42)).LT.0.1D-7) THEN
        V(43)=0.1D-7+V(47)+V(48)+V(49)-V(50)-V(51)-V(52)
     ELSE
     ENDIF
     V(53)=SQRT(V(43)-V(47)-V(48)-V(49)+V(50)+V(51)+V(52))
     V(74)=0.816496580927726D0*V(53)
     V(57)=(0.7348469228349535D1*(2D0*V(26)*V(27)*V(35)-V(40)*V(54)-V(41)*V(55)+V(42)*(V(40)*V(41)-V(56))))/V(53)**3
     V(58)=0D0
     IF(V(57).LE.(-1D0)) THEN
        V(58)=(-0.99999999D0)-V(57)
     ELSE
     ENDIF
     IF(V(57).GE.1D0) THEN
        V(58)=0.99999999D0-V(57)
     ELSE
     ENDIF
     V(62)=DACOS(V(57)+V(58))/3D0
     LPER2=MAX(MAX(V(39)+V(74)*DCOS(V(62)),V(39)-V(74)*DSIN(0.5235987755982988D0-V(62))),V(39)-V(74)*DSIN&
          &(0.5235987755982988D0+V(62)))
   END SUBROUTINE NPG_DRIVINGFORCE

   PURE SUBROUTINE NPG_MODIFIEDSE(VV,MUM,KM,A0,CE,PSI,SE,DSEDCE)
     IMPLICIT NONE
     DOUBLE PRECISION V(341),VV,MUM,KM,A0(3),CE(6),PSI,SE(6),DSEDCE(6,6)
     INTENT(IN) :: VV, MUM, KM, A0, CE
     INTENT(OUT) :: PSI, SE, DSEDCE
     V(321)=1D0-VV
     V(315)=A0(2)*CE(4)+A0(3)*CE(5)
     V(314)=2D0*A0(1)
     V(312)=CE(5)**2
     V(311)=CE(4)**2
     V(310)=CE(2)*CE(3)-CE(6)**2
     V(309)=(-2D0)*CE(6)
     V(308)=2D0*CE(5)
     V(307)=2D0*CE(4)
     V(313)=CE(5)*V(307)
     V(306)=CE(6)*V(307)-CE(2)*V(308)
     V(303)=CE(1)*CE(3)-V(312)
     V(301)=CE(1)*CE(2)-V(311)
     V(300)=A0(3)**2
     V(299)=A0(3)*V(314)
     V(298)=2D0*A0(2)
     V(297)=A0(2)**2
     V(296)=A0(1)*V(298)
     V(295)=A0(1)**2
     V(294)=(-0.5D0)*MUM
     V(293)=1D0+VV
     V(114)=A0(3)*V(298)
     V(106)=-(CE(3)*V(307))+CE(6)*V(308)
     V(108)=CE(1)*V(309)+V(313)
     V(81)=CE(1)*V(310)-CE(3)*V(311)-CE(2)*V(312)+CE(6)*V(313)
   !*** V(81)=det(Ce). A collapsed/inverted trial state (det<=0) would make the
   !*** SQRT/LOG/1-over-det below NaN/Inf and poison the residual; floor it to a
   !*** tiny positive value so the kernel stays finite and the global Newton cuts
   !*** the step (same guard as the neo-Hookean kernels in this file).
     IF(V(81).LE.0D0)V(81)=1D-12
     V(276)=DLOG(SQRT(V(81)))
     V(151)=1D0/SQRT(V(81))
     V(329)=V(151)/4D0
     V(91)=(-1D0)+SQRT(V(81))
     V(82)=CE(6)*V(114)+CE(1)*V(295)+CE(2)*V(297)+CE(3)*V(300)+V(314)*V(315)
   !*** V(82)=a0.Ce.a0 (fiber stretch^2), positive for admissible Ce; same floor
   !*** so the SQRT/1-over below stay finite on wild trial states.
     IF(V(82).LE.0D0)V(82)=1D-12
     V(318)=SQRT(V(81)/V(82))
     V(317)=1D0/SQRT(V(82))
     V(316)=1D0/(2D0*V(82))
     V(227)=1D0/V(82)**3
     V(222)=1D0/V(318)
     V(325)=(-2D0)*V(222)*V(227)
     V(218)=-(V(316)*V(317))
     V(116)=1D0/V(82)**2
     V(327)=V(116)*V(317)-V(218)/V(82)
     V(320)=-(V(116)*V(81))
     V(271)=1D0-V(317)/V(82)
     V(120)=1D0/V(318)**2
     V(319)=(-0.5D0)*(V(120)*V(222))
     V(129)=V(319)*(V(114)*V(320)+V(108)/V(82))
     V(127)=V(319)*(V(299)*V(320)+V(306)/V(82))
     V(125)=V(319)*(V(296)*V(320)+V(106)/V(82))
     V(123)=V(319)*(V(300)*V(320)+V(301)/V(82))
     V(121)=V(319)*(V(297)*V(320)+V(303)/V(82))
     V(118)=V(319)*(V(295)*V(320)+V(310)/V(82))
     V(270)=(-1D0)-V(222)*V(320)
     V(332)=V(271)+V(270)/V(293)
     V(135)=V(325)*V(81)
     V(161)=(KM*V(321))/4D0
     V(162)=-((V(161)*V(91))/V(81)**2)
     V(153)=(4D0*V(161))/V(81)
     V(90)=4D0*V(161)*V(276)
     V(160)=(-0.125D0)*V(90)/V(81)**0.15D1
     V(331)=V(160)+V(162)+V(153)*V(329)
     V(84)=-(V(294)*V(321))
     V(328)=V(84)/V(293)
     V(324)=-(V(328)/V(82))
     V(155)=V(222)*V(328)
     V(330)=V(116)*V(155)
     V(181)=V(129)*V(324)+V(114)*V(330)+V(108)*V(331)
     V(177)=V(127)*V(324)+V(299)*V(330)+V(306)*V(331)
     V(173)=V(125)*V(324)+V(296)*V(330)+V(106)*V(331)
     V(165)=V(121)*V(324)+V(297)*V(330)+V(303)*V(331)
     V(157)=V(118)*V(324)+V(295)*V(330)+V(310)*V(331)
     V(144)=(V(114)*V(327)+(V(114)*V(135)+V(116)*(V(108)*V(222)+V(129)*V(81)))/V(293))*V(84)
     V(213)=V(144)*V(300)+V(181)*V(301)
     V(212)=V(144)*V(297)+V(181)*V(303)
     V(150)=V(144)*V(314)
     V(142)=(V(299)*V(327)+(V(135)*V(299)+V(116)*(V(222)*V(306)+V(127)*V(81)))/V(293))*V(84)
     V(207)=V(142)*V(300)+V(177)*V(301)
     V(205)=V(142)*V(295)+V(177)*V(310)
     V(149)=V(142)*V(314)
     V(140)=(V(296)*V(327)+(V(135)*V(296)+V(116)*(V(106)*V(222)+V(125)*V(81)))/V(293))*V(84)
     V(198)=V(140)*V(297)+V(173)*V(303)
     V(197)=V(140)*V(295)+V(173)*V(310)
     V(136)=(V(297)*V(327)+(V(135)*V(297)+V(116)*(V(222)*V(303)+V(121)*V(81)))/V(293))*V(84)
     V(132)=(V(295)*V(327)+(V(135)*V(295)+V(116)*(V(222)*V(310)+V(118)*V(81)))/V(293))*V(84)
     V(89)=V(332)*V(84)
     V(333)=2D0*V(89)
     V(100)=A0(1)*V(333)
     V(93)=(((-4D0)*V(155))/V(82)+V(151)*V(90)+V(153)*V(91))/4D0
     V(336)=CE(3)*V(93)
     V(335)=CE(2)*V(93)
     V(334)=CE(1)*V(93)
     V(209)=-(V(307)*V(93))
     V(203)=-(V(308)*V(93))
     V(206)=V(203)+V(142)*V(297)+V(177)*V(303)
     V(201)=V(309)*V(93)
     V(211)=V(201)+V(144)*V(295)+V(181)*V(310)
     V(199)=V(209)+V(140)*V(300)+V(173)*V(301)
     V(183)=2D0*(V(132)*V(297)+V(157)*V(303)+V(336))
     V(184)=2D0*(V(132)*V(300)+V(157)*V(301)+V(335))
     V(186)=2D0*(V(136)*V(300)+V(165)*V(301)+V(334))
     V(202)=A0(2)*V(149)+V(106)*V(177)-V(201)
     V(204)=A0(2)*V(150)+V(106)*V(181)-V(203)
     V(210)=A0(3)*V(150)-V(209)+V(181)*V(306)
     PSI=((-3D0)+2D0*V(317)+(CE(1)+CE(2)+CE(3)-2D0*V(318)-V(82))/V(293)+V(82))*V(84)+(V(90)*V(91))/2D0
     SE(1)=2D0*(V(328)+V(295)*V(89)+V(310)*V(93))
     SE(2)=2D0*(V(328)+V(297)*V(89)+V(303)*V(93))
     SE(3)=2D0*(V(328)+V(300)*V(89)+V(301)*V(93))
     SE(4)=A0(2)*V(100)+V(106)*V(93)
     SE(5)=A0(3)*V(100)+V(306)*V(93)
     SE(6)=V(114)*V(89)+V(108)*V(93)
     DSEDCE(1,1)=2D0*(V(132)*V(295)+V(157)*V(310))
     DSEDCE(1,2)=V(183)
     DSEDCE(1,3)=V(184)
     DSEDCE(1,4)=2D0*V(197)
     DSEDCE(1,5)=2D0*V(205)
     DSEDCE(1,6)=2D0*V(211)
     DSEDCE(2,1)=V(183)
     DSEDCE(2,2)=2D0*(V(136)*V(297)+V(165)*V(303))
     DSEDCE(2,3)=V(186)
     DSEDCE(2,4)=2D0*V(198)
     DSEDCE(2,5)=2D0*V(206)
     DSEDCE(2,6)=2D0*V(212)
     DSEDCE(3,1)=V(184)
     DSEDCE(3,2)=V(186)
     DSEDCE(3,3)=2D0*(V(301)*(V(123)*V(324)+V(300)*V(330)+V(301)*V(331))+V(300)*(V(300)*V(327)+(V(135)*V(300)+V(116)*(V(222&
          &)*V(301)+V(123)*V(81)))/V(293))*V(84))
     DSEDCE(3,4)=2D0*V(199)
     DSEDCE(3,5)=2D0*V(207)
     DSEDCE(3,6)=2D0*V(213)
     DSEDCE(4,1)=V(197)
     DSEDCE(4,2)=V(198)
     DSEDCE(4,3)=V(199)
     DSEDCE(4,4)=V(106)*V(173)+V(140)*V(296)-2D0*V(336)
